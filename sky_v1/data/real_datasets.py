"""Real public dataset loader with multi-mirror source fallback.

Implements spec §11: 数据集下载失败 → 脚本提供 Toy Dataset + 公开数据集多镜像源.

The loader wraps ``datasets.load_dataset`` so callers can stay oblivious to
whether the public dataset was actually reachable. ``load`` always returns a
non-empty ``list[dict]``; when the requested public dataset cannot be fetched
(missing ``datasets`` lib, network unreachable, unknown dataset name, test
mode, ...) it deterministically falls back to toy samples generated by
``ToyDataGenerator`` so downstream training pipelines can always start.

Supported sources (mirrors):
    - hf        : HuggingFace datasets hub (huggingface.co)
    - aliyun    : Aliyun Tianchi HF mirror (hf-mirror.com, mainland China)
    - modelscope: ModelScope 魔搭社区 (modelscope.cn) via ``MsDataset``
"""
from __future__ import annotations

import os
from typing import Any, Iterator

from .toy_generator import ToyDataGenerator


class RealDatasetLoader:
    """Wrap ``datasets.load_dataset`` calls with multi-mirror source fallback.

    Construction is cheap and side-effect free; the heavy ``datasets`` /
    ``modelscope`` imports happen lazily inside ``load`` so environments
    without those libraries can still instantiate the loader and use it.
    """

    SOURCES = ["hf", "aliyun", "modelscope"]

    # Mirror endpoints (HF_ENDPOINT convention used by the `datasets` lib).
    _ALIYUN_ENDPOINT = "https://hf-mirror.com"
    _MODELSCOPE_BASE = "https://www.modelscope.cn"
    _HF_DEFAULT_ENDPOINT = "https://huggingface.co"

    # Logical-name -> HuggingFace dataset id mapping. Keeping this explicit
    # lets callers ask for ``"alpaca"`` without remembering the org/slug.
    _HF_IDS: dict[str, str] = {
        # ---- pretrain corpora ----
        "redpajama": "togethercomputer/RedPajama-Data-1T-Sample",
        "wikipedia": "wikimedia/wikipedia",
        "openwebtext": "Skylion007/openwebtext",
        # ---- SFT instruction ----
        "alpaca": "yahma/alpaca-cleaned",
        "dolly": "databricks/databricks-dolly-15k",
        "orca": "Open-Orca/OpenOrca",
        "ultrachat": "HuggingFaceH4/ultrachat_200k",
        # ---- preference pairs (DPO) ----
        "ultrafeedback": "argilla/ultrafeedback-binarized-preferences-cleaned",
        "hh-rlhf": "Anthropic/hh-rlhf",
        # ---- multimodal ----
        "coco_captions": "HuggingFaceM4/COCO",
        "laion_400m_sample": "laion/laion400m",
        "librispeech": "openslr/librispeech_asr",
        "audioset": "agkphysics/AudioSet",
        "msr_vtt": "Shuhong/MSR-VTT",
        "webvid": "pipiluv/webvid10m",
        "shapenet": "cchangdock/shapenet",
        "objaverse": "dyxu/Objaverse",
    }

    _PRETRAIN_DATASETS = ["redpajama", "wikipedia", "openwebtext"]
    _SFT_DATASETS = ["alpaca", "dolly", "orca", "ultrachat"]
    _PREFERENCE_DATASETS = ["ultrafeedback", "hh-rlhf"]
    _MODAL_DATASETS: dict[str, list[str]] = {
        "image": ["coco_captions", "laion_400m_sample"],
        "audio": ["librispeech", "audioset"],
        "video": ["msr_vtt", "webvid"],
        "3d": ["shapenet", "objaverse"],
    }

    TOY_DEFAULT_SIZE = 16

    def __init__(self) -> None:
        # Intentionally empty: heavy imports are deferred to ``load`` so the
        # loader can be constructed in environments without `datasets`.
        pass

    # ------------------------------------------------------------------ #
    # public API
    # ------------------------------------------------------------------ #
    def list_available(self) -> dict[str, list[str]]:
        """Return available dataset lists grouped by category.

        Always returns a fresh dict (callers may mutate safely).
        """
        return {
            "pretrain": list(self._PRETRAIN_DATASETS),
            "sft": list(self._SFT_DATASETS),
            "preference": list(self._PREFERENCE_DATASETS),
            "modal_image": list(self._MODAL_DATASETS["image"]),
            "modal_audio": list(self._MODAL_DATASETS["audio"]),
            "modal_video": list(self._MODAL_DATASETS["video"]),
            "modal_3d": list(self._MODAL_DATASETS["3d"]),
            "sources": list(self.SOURCES),
        }

    def load(
        self,
        dataset_name: str,
        split: str = "train",
        source: str = "hf",
        max_samples: int | None = None,
    ) -> list[dict[str, Any]]:
        """Load ``dataset_name`` from ``source``; fall back to toy on any failure.

        Args:
            dataset_name: logical name (e.g. ``"alpaca"``) or a raw HF id.
            split: dataset split (default ``"train"``).
            source: one of :attr:`SOURCES`. Unknown values fall back to toy.
            max_samples: cap the returned list length; ``None`` means no cap
                (toy path still uses :attr:`TOY_DEFAULT_SIZE` when ``None``).

        Returns:
            Non-empty ``list[dict]``. Toy samples carry ``"toy": True``.
        """
        if source not in self.SOURCES:
            print(
                f"[RealDatasetLoader] unknown source={source!r}; "
                f"supported={self.SOURCES}; fallback to toy"
            )
            return self._toy_samples(dataset_name, max_samples)

        # In test mode, never hit the network even if `datasets` is installed.
        if os.environ.get("SKY_V1_TEST_MODE") == "1":
            print(
                f"[RealDatasetLoader] SKY_V1_TEST_MODE=1; skipping real "
                f"download of {dataset_name!r}; fallback to toy"
            )
            return self._toy_samples(dataset_name, max_samples)

        try:
            if source == "modelscope":
                data = self._try_load_modelscope(dataset_name, split, max_samples)
            else:
                data = self._try_load_hf(dataset_name, split, source, max_samples)
        except Exception as e:  # noqa: BLE001 - we explicitly want broad catch
            print(
                f"[RealDatasetLoader] load {dataset_name!r} from {source!r} "
                f"failed: {type(e).__name__}: {e}; fallback to toy"
            )
            return self._toy_samples(dataset_name, max_samples)

        if not data:
            print(
                f"[RealDatasetLoader] empty result for {dataset_name!r} from "
                f"{source!r}; fallback to toy"
            )
            return self._toy_samples(dataset_name, max_samples)
        return data

    # ------------------------------------------------------------------ #
    # internal: real-data fetchers (lazy import; may raise)
    # ------------------------------------------------------------------ #
    def _resolve_endpoint(self, source: str) -> str:
        if source == "aliyun":
            return self._ALIYUN_ENDPOINT
        if source == "modelscope":
            return self._MODELSCOPE_BASE
        return os.environ.get("HF_ENDPOINT", self._HF_DEFAULT_ENDPOINT)

    def _try_load_hf(
        self,
        dataset_name: str,
        split: str,
        source: str,
        max_samples: int | None,
    ) -> list[dict[str, Any]]:
        """Try HuggingFace ``datasets.load_dataset``; may raise any Exception."""
        import datasets  # lazy: ImportError surfaces to ``load``

        hf_id = self._HF_IDS.get(dataset_name, dataset_name)
        endpoint = self._resolve_endpoint(source)
        prev_endpoint = os.environ.get("HF_ENDPOINT")
        os.environ["HF_ENDPOINT"] = endpoint
        try:
            # Streaming first: avoids downloading the full dataset to disk.
            try:
                ds = datasets.load_dataset(hf_id, split=split, streaming=True)
            except Exception:
                ds = datasets.load_dataset(hf_id, split=split)
        finally:
            if prev_endpoint is None:
                os.environ.pop("HF_ENDPOINT", None)
            else:
                os.environ["HF_ENDPOINT"] = prev_endpoint

        return self._iter_to_list(ds, max_samples)

    def _try_load_modelscope(
        self,
        dataset_name: str,
        split: str,
        max_samples: int | None,
    ) -> list[dict[str, Any]]:
        """Try ModelScope ``MsDataset.load``; may raise any Exception."""
        from modelscope.msdatasets import MsDataset  # lazy import

        ms_id = self._HF_IDS.get(dataset_name, dataset_name)
        ds = MsDataset.load(ms_id, split=split)
        return self._iter_to_list(ds, max_samples)

    @staticmethod
    def _iter_to_list(iterable: Any, max_samples: int | None) -> list[dict[str, Any]]:
        out: list[dict[str, Any]] = []
        it: Iterator[Any] = iter(iterable)
        for i, item in enumerate(it):
            if max_samples is not None and i >= max_samples:
                break
            if isinstance(item, dict):
                out.append(item)
            else:
                # Wrap non-dict items (e.g. raw strings) so the contract holds.
                out.append({"value": item})
        return out

    # ------------------------------------------------------------------ #
    # internal: deterministic toy fallback
    # ------------------------------------------------------------------ #
    def _toy_samples(
        self,
        dataset_name: str,
        max_samples: int | None,
    ) -> list[dict[str, Any]]:
        n = max_samples if (max_samples is not None and max_samples > 0) else self.TOY_DEFAULT_SIZE
        gen = ToyDataGenerator(n=n, seed=42, vocab_size=1000)
        out: list[dict[str, Any]] = []
        for s in gen.generate_all():
            text_ids = s["text_ids"]
            try:
                ids_list = [str(int(x)) for x in text_ids.tolist()]
            except Exception:
                ids_list = [str(int(x)) for x in text_ids.reshape(-1).tolist()]
            out.append({
                "id": s.get("id", ""),
                "text": " ".join(ids_list),
                "source": dataset_name,
                "toy": True,
            })
        return out
